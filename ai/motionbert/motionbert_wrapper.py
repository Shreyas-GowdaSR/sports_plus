"""Legacy transformer experiment; not MotionBERT and not validated 3D lifting.

Its training targets are generated by `_synth_data`, not measured 3D poses.
Predicted depth is synthetic-model output and must not be reported as real
biomechanics or used as validated evidence in a research claim.
"""
import json, math, time
from pathlib import Path
from typing import List
import numpy as np
import torch
import torch.nn as nn

H36M_NAMES = [
    "hip_centre","right_hip","right_knee","right_ankle",
    "left_hip","left_knee","left_ankle","spine","neck",
    "nose","head","left_shoulder","left_elbow","left_wrist",
    "right_shoulder","right_elbow","right_wrist",
]
MP_TO_H36M = {
    "hip_centre":[23,24],"right_hip":[24],"right_knee":[26],"right_ankle":[28],
    "left_hip":[23],"left_knee":[25],"left_ankle":[27],
    "spine":[23,24,11,12],"neck":[11,12],"nose":[0],"head":[0],
    "left_shoulder":[11],"left_elbow":[13],"left_wrist":[15],
    "right_shoulder":[12],"right_elbow":[14],"right_wrist":[16],
}
N_JOINTS = 17
SEQ_LEN  = 27
MODEL_PATH = Path(__file__).parent / "lifting_model.pt"


class PositionalEncoding(nn.Module):
    def __init__(self, d_model, max_len=512, dropout=0.1):
        super().__init__()
        self.dropout = nn.Dropout(p=dropout)
        pe  = torch.zeros(max_len, d_model)
        pos = torch.arange(0, max_len).unsqueeze(1).float()
        div = torch.exp(torch.arange(0, d_model, 2).float() * (-math.log(10000.0)/d_model))
        pe[:,0::2] = torch.sin(pos*div); pe[:,1::2] = torch.cos(pos*div)
        self.register_buffer("pe", pe.unsqueeze(0))
    def forward(self, x):
        return self.dropout(x + self.pe[:, :x.size(1)])


class LiftingTransformer(nn.Module):
    def __init__(self, n_joints=N_JOINTS, d_model=128, n_heads=4, n_layers=4, d_ff=256, dropout=0.1):
        super().__init__()
        self.input_proj = nn.Sequential(
            nn.Linear(n_joints*2, d_model), nn.LayerNorm(d_model), nn.ReLU())
        self.pos_enc = PositionalEncoding(d_model, dropout=dropout)
        enc_layer = nn.TransformerEncoderLayer(
            d_model=d_model, nhead=n_heads, dim_feedforward=d_ff,
            dropout=dropout, batch_first=True, norm_first=True)
        self.transformer = nn.TransformerEncoder(enc_layer, num_layers=n_layers, norm=nn.LayerNorm(d_model))
        self.output_head = nn.Sequential(
            nn.Linear(d_model, d_model//2), nn.ReLU(),
            nn.Dropout(dropout), nn.Linear(d_model//2, n_joints*3))
        self.n_joints = n_joints

    def forward(self, x):
        B,T,J,C = x.shape
        x_flat = x.reshape(B,T,J*C)
        x_emb  = self.pos_enc(self.input_proj(x_flat))
        x_enc  = self.transformer(x_emb)
        return self.output_head(x_enc).reshape(B,T,J,3)


def _synth_data(n=1500, seq_len=SEQ_LEN):
    base = np.array([
        [0.00,0.00,0.00],[0.10,0.00,0.00],[0.10,-0.45,0.02],[0.10,-0.90,0.00],
        [-0.10,0.00,0.00],[-0.10,-0.45,0.02],[-0.10,-0.90,0.00],
        [0.00,0.20,0.00],[0.00,0.45,0.00],[0.00,0.55,0.02],[0.00,0.60,0.02],
        [-0.18,0.40,0.00],[-0.18,0.10,-0.10],[-0.18,-0.15,-0.15],
        [0.18,0.40,0.00],[0.18,0.10,-0.10],[0.18,-0.15,-0.15],
    ], dtype=np.float32)
    X2d, Y3d = [], []
    for _ in range(n):
        seq3d = np.zeros((seq_len, N_JOINTS, 3), dtype=np.float32)
        for t in range(seq_len):
            phase = t/seq_len
            m = np.zeros((N_JOINTS,3), dtype=np.float32)
            bend = 0.15*np.sin(2*np.pi*phase)
            m[2]=[0,bend,0]; m[5]=[0,bend,0]
            swing = 0.08*np.sin(2*np.pi*phase)
            m[12]=[0,swing,swing]; m[15]=[0,-swing,-swing]
            seq3d[t] = base + m + np.random.randn(N_JOINTS,3).astype(np.float32)*0.02
        seq2d = seq3d[:,:,:2].copy()
        seq2d += np.random.randn(*seq2d.shape).astype(np.float32)*0.01
        rng = seq2d.max()-seq2d.min()+1e-8
        seq2d = (seq2d-seq2d.min())/rng
        X2d.append(seq2d); Y3d.append(seq3d)
    return np.array(X2d,dtype=np.float32), np.array(Y3d,dtype=np.float32)


def train_and_save(epochs=25, batch=32, lr=1e-3):
    print("[MotionBERT] Training 3D lifting transformer...")
    device = torch.device("cuda" if torch.cuda.is_available() else "cpu")
    X,Y   = _synth_data(n=1500, seq_len=SEQ_LEN)
    split = int(0.85*len(X))
    Xtr,Ytr = torch.FloatTensor(X[:split]).to(device), torch.FloatTensor(Y[:split]).to(device)
    Xva,Yva = torch.FloatTensor(X[split:]).to(device), torch.FloatTensor(Y[split:]).to(device)
    model = LiftingTransformer().to(device)
    opt   = torch.optim.AdamW(model.parameters(), lr=lr, weight_decay=1e-4)
    sched = torch.optim.lr_scheduler.CosineAnnealingLR(opt, T_max=epochs)
    crit  = nn.MSELoss()
    best  = float("inf")
    for ep in range(1, epochs+1):
        model.train()
        idx = torch.randperm(len(Xtr))
        ls, nb = 0.0, 0
        for i in range(0, len(Xtr), batch):
            bi = idx[i:i+batch]; xb,yb = Xtr[bi],Ytr[bi]
            opt.zero_grad(); loss = crit(model(xb),yb)
            loss.backward(); nn.utils.clip_grad_norm_(model.parameters(),1.0); opt.step()
            ls += loss.item(); nb += 1
        sched.step()
        model.eval()
        with torch.no_grad(): vl = crit(model(Xva),Yva).item()
        if vl < best: best=vl; torch.save(model.state_dict(), MODEL_PATH)
        if ep%5==0: print(f"  ep={ep}/{epochs} val={vl:.5f} best={best:.5f}")
    print(f"[MotionBERT] Done. val_loss={best:.5f} → {MODEL_PATH}")
    return model, device


class MotionBERTWrapper:
    def __init__(self):
        self.device = torch.device("cuda" if torch.cuda.is_available() else "cpu")
        self.model  = LiftingTransformer().to(self.device)
        if MODEL_PATH.exists():
            self.model.load_state_dict(torch.load(MODEL_PATH, map_location=self.device))
            print(f"[MotionBERT] Loaded weights ← {MODEL_PATH}")
        else:
            print("[MotionBERT] Training model (first run)...")
            self.model, self.device = train_and_save()
        self.model.eval()

    def _mp_to_h36m(self, landmarks):
        lm_xy = np.zeros((33,2), dtype=np.float32)
        for lm in landmarks:
            idx = lm.get("id",-1)
            if 0 <= idx < 33:
                lm_xy[idx] = [lm.get("x",0.0), lm.get("y",0.0)]
        h36m = np.zeros((N_JOINTS,2), dtype=np.float32)
        for i,name in enumerate(H36M_NAMES):
            indices = MP_TO_H36M[name]
            h36m[i] = [np.mean([lm_xy[j][0] for j in indices]),
                       np.mean([lm_xy[j][1] for j in indices])]
        return h36m

    def _lift(self, seq2d):
        T = seq2d.shape[0]
        results = np.zeros((T,N_JOINTS,3), dtype=np.float32)
        counts  = np.zeros(T, dtype=np.float32)
        W = SEQ_LEN
        starts = list(range(0, max(1,T-W+1), W//2)) or [0]
        with torch.no_grad():
            for s in starts:
                e = min(s+W,T)
                chunk = seq2d[s:e]
                if len(chunk)<W:
                    pad   = np.zeros((W-len(chunk),N_JOINTS,2), dtype=np.float32)
                    chunk = np.concatenate([chunk,pad],axis=0)
                x   = torch.FloatTensor(chunk).unsqueeze(0).to(self.device)
                out = self.model(x).squeeze(0).cpu().numpy()
                actual = min(W,T-s)
                results[s:s+actual] += out[:actual]
                counts[s:s+actual]  += 1
        counts = np.maximum(counts,1)
        return results / counts[:,None,None]

    def run(self, frames):
        if not frames: return {"status":"empty","num_frames":0,"skeleton3d":[],"lifted_3d":[]}
        t0    = time.perf_counter()
        seq2d = np.array([self._mp_to_h36m(f.get("landmarks",[])) for f in frames], dtype=np.float32)
        seq3d = self._lift(seq2d)
        ms    = (time.perf_counter()-t0)*1000
        enriched = []
        for fi,frame in enumerate(frames):
            new_lm = [dict(lm) for lm in frame.get("landmarks",[])]
            for lm in new_lm:
                lm["z_lifted"] = float(seq3d[fi,0,2])
            enriched.append({**frame,"landmarks":new_lm})
        print(f"[MotionBERT] {len(frames)} frames lifted in {ms:.1f}ms")
        return {"status":"completed","num_frames":len(frames),"skeleton3d":enriched,"lifted_3d":seq3d.tolist(),"latency_ms":round(ms,2)}
